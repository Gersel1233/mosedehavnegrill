--  skraldespanden, hvor alt skal ligge og gendannes, hvis det giver
--  mening"* — og *"når man sletter noget, skal kalenderen altså
--  følge med og systemet med det samme"*.
--
--  skraldespand.sql (august) dækkede de fire, en GÆST har skrevet:
--  bestillinger, forespørgsler, bordbookinger og udlejninger. Alt
--  det, personalet selv laver — arrangementer, lukkedage og noter i
--  kalenderen, nyheder, menukortets kategorier og varer, dagens
--  retter, rabatkoder og borde — var væk for altid ved ét fejltryk.
--
--  ------------------------------------------------------------
--  SÅDAN VIRKER DEN
--  ------------------------------------------------------------
--  Rækken slettes stadig for alvor fra sin egen tabel. Derfor
--  følger kalenderen, forsiden og alle lister med i samme sekund —
--  ingen liste skal lære at springe "slettede" over, og intet
--  slettet kan dukke op på hjemmesiden ved en fejl.
--
--  Lige før den forsvinder, lægger en udløser en KOPI i
--  skraldespand_arkiv. "Hent tilbage" (mosede_gendan_arkiv) sætter
--  kopien ind igen med samme id — og databasens egne regler gælder
--  for den, der henter tilbage: en arrangør kan hente et arrangement,
--  ikke en lukkedag. Efter 30 dage tømmes arkivet (admin gør det ved
--  login, som med den gamle spand).
--
--  Sletter man en menukategori, går dens varer med (on delete
--  cascade). De ligger i arkivet sammen med kategorien og kommer
--  tilbage sammen med den.
--
--  ⚠️ TILMELDINGER ER IKKE MED. De har allerede deres egen
--  "slettet"-kolonne, og et arrangement med tilmeldte kan slet ikke
--  slettes (kalender_slet_vaern) — det aflyses.
-- ============================================================

begin;

-- ------------------------------------------------------------
-- 1) ARKIVET
-- ------------------------------------------------------------
create table if not exists public.skraldespand_arkiv (
  id          bigint generated by default as identity primary key,
  lokation_id text        not null,
  tabel       text        not null,
  raekke_id   text        not null,
  raekke      jsonb       not null,
  -- true = det, nogen trykkede Slet på. false = det, der fulgte med
  -- (en kategoris varer). Kun hovedrækkerne står i spanden; de andre
  -- kommer med, når hovedrækken hentes tilbage.
  hoved       boolean     not null default true,
  gruppe      bigint      not null default txid_current(),
  slettet     timestamptz not null default now(),
  slettet_af  text
);

create index if not exists skraldespand_arkiv_slettet_idx
  on public.skraldespand_arkiv (lokation_id, slettet desc);
create index if not exists skraldespand_arkiv_gruppe_idx
  on public.skraldespand_arkiv (gruppe);

grant select, delete on public.skraldespand_arkiv to authenticated;
revoke all on public.skraldespand_arkiv from anon;

alter table public.skraldespand_arkiv enable row level security;

-- Læse og slette for altid: personalet (ikke arrangøren) ser alt;
-- arrangøren ser sine egne slags — arrangementer og nyheder.
drop policy if exists skraldespand_arkiv_laes on public.skraldespand_arkiv;
create policy skraldespand_arkiv_laes on public.skraldespand_arkiv
  for select using (
    public.is_admin_for(lokation_id)
    or (public.kan_arrangere_for(lokation_id)
        and (tabel = 'nyheder'
             or (tabel = 'kalender' and raekke ->> 'type' = 'arrangement')))
  );

drop policy if exists skraldespand_arkiv_slet on public.skraldespand_arkiv;
create policy skraldespand_arkiv_slet on public.skraldespand_arkiv
  for delete using (
    public.is_admin_for(lokation_id)
    or (public.kan_arrangere_for(lokation_id)
        and (tabel = 'nyheder'
             or (tabel = 'kalender' and raekke ->> 'type' = 'arrangement')))
  );
-- Ingen insert- eller update-regel: kun udløseren skriver her.


-- ------------------------------------------------------------
-- 2) UDLØSEREN — en kopi, lige før rækken forsvinder
--    security definer: personalet må ikke skrive i arkivet selv.
--    pg_trigger_depth() > 1 = rækken gik med i en kaskade (en
--    kategoris varer) og er ikke en, nogen trykkede Slet på.
-- ------------------------------------------------------------
create or replace function public.mosede_til_arkiv()
 returns trigger
 language plpgsql
 security definer
 set search_path to ''
as $function$
begin
  insert into public.skraldespand_arkiv
    (lokation_id, tabel, raekke_id, raekke, hoved, slettet_af)
  values
    (old.lokation_id, tg_table_name, old.id::text, to_jsonb(old),
     pg_trigger_depth() <= 1,
     nullif(coalesce(auth.jwt() ->> 'email', ''), ''));
  return old;
end $function$;

do $$
declare
  t text;
begin
  foreach t in array array['kalender', 'nyheder', 'menu_kategorier', 'menu_varer',
                           'dagens_retter', 'rabatkoder', 'borde'] loop
    if to_regclass('public.' || t) is null then
      raise notice 'Tabellen % findes ikke — springes over', t;
      continue;
    end if;
    execute format('drop trigger if exists til_skraldespand on public.%I', t);
    -- ⚠️ BEFORE, ikke after: en kaskade (kategoriens varer) kører sine
    -- before-udløsere INDE i forælderens sletning (dybde 2), så
    -- pg_trigger_depth kan skelne. After-udløsere køres i kø bagefter,
    -- på dybde 1, og så lignede varerne nogle, nogen havde slettet.
    -- Fejler sletningen (fx kalender_slet_vaern), rulles kopien med.
    execute format('create trigger til_skraldespand before delete on public.%I '
                   'for each row execute function public.mosede_til_arkiv()', t);
  end loop;
end $$;


-- ------------------------------------------------------------
-- 3) HENT TILBAGE
--    ⚠️ SECURITY INVOKER MED VILJE. Indsættelsen går gennem
--    tabellens egne adgangsregler og værn — den, der henter
--    tilbage, kan præcis det, vedkommende kunne oprette i forvejen.
--    Hovedrækken først, så det, der fulgte med (kategoriens varer).
-- ------------------------------------------------------------
create or replace function public.mosede_gendan_arkiv(p_id bigint)
 returns integer
 language plpgsql
 security invoker
 set search_path to ''
as $function$
declare
  a public.skraldespand_arkiv;
  r public.skraldespand_arkiv;
  n integer := 0;
begin
  select * into a from public.skraldespand_arkiv where id = p_id;
  if a.id is null then
    raise exception 'skraldespand_findes_ikke';
  end if;
  if a.tabel not in ('kalender', 'nyheder', 'menu_kategorier', 'menu_varer',
                     'dagens_retter', 'rabatkoder', 'borde') then
    raise exception 'skraldespand_ukendt_tabel';
  end if;

  begin
    execute format('insert into public.%I select * from jsonb_populate_record(null::public.%I, $1)',
                   a.tabel, a.tabel) using a.raekke;
  exception when unique_violation then
    raise exception 'skraldespand_findes_allerede';
  end;
  n := 1;

  -- Det, der fulgte med i samme sletning (en kategoris varer).
  if a.tabel = 'menu_kategorier' then
    for r in select * from public.skraldespand_arkiv
              where gruppe = a.gruppe and tabel = 'menu_varer' and not hoved
                and raekke ->> 'kategori_id' = a.raekke_id
    loop
      begin
        insert into public.menu_varer
          select * from jsonb_populate_record(null::public.menu_varer, r.raekke);
        delete from public.skraldespand_arkiv where id = r.id;
        n := n + 1;
      exception when unique_violation then
        null;  -- varen findes allerede; spring den over
      end;
    end loop;
  end if;

  delete from public.skraldespand_arkiv where id = a.id;
  return n;
end $function$;

grant execute on function public.mosede_gendan_arkiv(bigint) to authenticated;
revoke execute on function public.mosede_gendan_arkiv(bigint) from anon;

commit;

-- Editoren viser kun den sidste sætnings svar — derfor en select.
select 'Skraldespanden tager nu også arrangementer, kalender, nyheder, menukort, '
       || 'dagens retter, rabatkoder og borde — 30 dage, og de kan hentes tilbage'
  as resultat;
