-- ============================================================
--  RABATKODER TIL AFTALE-KUNDER  (28/10 2026)
--  ------------------------------------------------------------
--  Mikkel: *"hvad hvis man vil lave nogle priser om derinde [i
--  smørrebrød ud af huset] … så dem, der har lavet en ordning,
--  fik lidt rabat — det er jo fair — men det kan man ikke
--  administrere, men det skal man"*. Hans valg samme aften:
--  en RABATKODE til aftalerne.
--
--  Sådan virker det:
--    · ejeren/personalet laver en kode i admin (Bestillinger →
--      Aftaler og rabatkoder): fx GREVEKOMMUNE = 10 %
--    · gæsten skriver koden på bestil-siden og ser rabatten
--    · DATABASEN regner rabatten ud — aldrig browseren. Linjernes
--      priser røres ikke (prisværnet står urørt); rabatten står
--      for sig: rabat_kode, rabat_navn, rabat_procent, rabat_kr
--    · der betales ved lugen, og bonen siger "Aftale: … −32 kr."
--
--  ⚠️ KODERNE ER HEMMELIGE. Gæsten kan ikke læse tabellen — kun
--     spørge om ÉN kode (mosede_tjek_rabatkode), som hun selv har.
--  ⚠️ En forkert kode afviser bestillingen med 'rabatkode_ugyldig',
--     og siden siger det på dansk. Ingen kode = ingen rabat, som før.
--
--  Kan køres igen. Kør den i Mosede-projektet (epwyjzakvvbxtpvnhvbn).
--  Prøven er supabase/proev-rabatkoder-28-10.sql.
-- ============================================================
begin;

create table if not exists public.rabatkoder (
  id          bigint generated by default as identity primary key,
  lokation_id text not null default 'mosede' references public.lokationer(id) on delete cascade,
  kode        text not null,
  navn        text not null,
  procent     int  not null,
  aktiv       boolean not null default true,
  oprettet    timestamptz not null default now(),
  constraint rabatkode_kode_ok check (kode ~ '^[A-Z0-9ÆØÅ-]{3,30}$'),
  constraint rabatkode_navn_ok check (length(btrim(navn)) between 1 and 80),
  constraint rabatkode_procent_ok check (procent between 1 and 50)
);
create unique index if not exists rabatkode_unik on public.rabatkoder (lokation_id, kode);
comment on table public.rabatkoder is
  'Rabatkoder til aftale-kunder (fx en virksomhed med en frokostordning). Kun personalet kan se dem; gæsten kan kun spørge om én kode via mosede_tjek_rabatkode.';

alter table public.rabatkoder enable row level security;
revoke all on public.rabatkoder from anon;
drop policy if exists rabatkoder_laes on public.rabatkoder;
create policy rabatkoder_laes on public.rabatkoder for select using (public.is_admin_for(lokation_id));
drop policy if exists rabatkoder_opret on public.rabatkoder;
create policy rabatkoder_opret on public.rabatkoder for insert with check (public.is_admin_for(lokation_id));
drop policy if exists rabatkoder_ret on public.rabatkoder;
create policy rabatkoder_ret on public.rabatkoder for update
  using (public.is_admin_for(lokation_id)) with check (public.is_admin_for(lokation_id));
drop policy if exists rabatkoder_slet on public.rabatkoder;
create policy rabatkoder_slet on public.rabatkoder for delete using (public.is_admin_for(lokation_id));

-- ------------------------------------------------------------
--  Rabatten på bestillingen — fire kolonner, som databasen fylder
-- ------------------------------------------------------------
alter table public.bestillinger add column if not exists rabat_kode text;
alter table public.bestillinger add column if not exists rabat_navn text;
alter table public.bestillinger add column if not exists rabat_procent int;
alter table public.bestillinger add column if not exists rabat_kr numeric(10, 2);

/* ⚠️ BROWSEREN SENDER KUN KODEN. Navn, procent og beløb sættes HER,
   uanset hvad der blev sendt — ellers kunne en gæst skrive sin egen
   rabat. Beløbet er linjernes pris × antal × procent, rundet til hele
   kroner. Kører SIDST blandt BEFORE-udløserne (navnet zz_…), så de
   priser, den regner på, er dem, prisværnet har godkendt. */
create or replace function public.mosede_rabatkode()
 returns trigger
 language plpgsql
 security definer
 set search_path to ''
as $function$
declare
  r public.rabatkoder;
  sum_kr numeric;
begin
  if nullif(btrim(coalesce(new.rabat_kode, '')), '') is null then
    new.rabat_kode := null; new.rabat_navn := null; new.rabat_procent := null; new.rabat_kr := null;
    return new;
  end if;
  select * into r from public.rabatkoder k
   where k.lokation_id = new.lokation_id and k.kode = upper(btrim(new.rabat_kode)) and k.aktiv
   limit 1;
  if r.id is null then
    raise exception 'rabatkode_ugyldig';
  end if;
  select coalesce(sum(
           case when jsonb_typeof(l -> 'pris') = 'number' and jsonb_typeof(l -> 'antal') = 'number'
                then (l ->> 'pris')::numeric * greatest((l ->> 'antal')::numeric, 0) else 0 end), 0)
    into sum_kr
    from jsonb_array_elements(coalesce(new.linjer, '[]'::jsonb)) l;
  new.rabat_kode := r.kode;
  new.rabat_navn := r.navn;
  new.rabat_procent := r.procent;
  new.rabat_kr := round(sum_kr * r.procent / 100.0);
  return new;
end $function$;

revoke all on function public.mosede_rabatkode() from public, anon, authenticated;

drop trigger if exists zz_rabatkode on public.bestillinger;
create trigger zz_rabatkode
  before insert on public.bestillinger
  for each row execute function public.mosede_rabatkode();

/* Rabatten kan ikke rettes bagefter af en gæst (gæsten kan slet ikke
   rette), og personalets rettelser rører den ikke — udløseren er kun
   ved indsættelsen. */

-- ------------------------------------------------------------
--  GÆSTENS SPØRGSMÅL: "gælder min kode?" — ÉN kode ad gangen
-- ------------------------------------------------------------
create or replace function public.mosede_tjek_rabatkode(kode text, lok text default 'mosede')
 returns table (navn text, procent int)
 language sql
 stable
 security definer
 set search_path to ''
as $function$
  /* ⚠️ $1 OG $2, IKKE NAVNENE. I en SQL-funktion vinder kolonnen over
     parameteren: "k.kode = upper(btrim(kode))" sammenlignede kolonnen
     med sig selv, og ENHVER kode svarede med den første aftale. Fundet
     af proev-rabatkoder-28-10.sql (prøve 3), før filen kom ud. */
  select k.navn, k.procent from public.rabatkoder k
   where k.lokation_id = $2 and k.kode = upper(btrim($1)) and k.aktiv
   limit 1
$function$;
revoke all on function public.mosede_tjek_rabatkode(text, text) from public;
grant execute on function public.mosede_tjek_rabatkode(text, text) to anon, authenticated;

commit;

notify pgrst, 'reload schema';

select case when to_regclass('public.rabatkoder') is not null
             and exists (select 1 from pg_trigger where tgname = 'zz_rabatkode')
             and exists (select 1 from information_schema.columns
                          where table_schema = 'public' and table_name = 'bestillinger' and column_name = 'rabat_kr')
            then '✅ Rabatkoderne er klar — lav dem i admin under Bestillinger'
            else '❌ Noget gik galt — sig til Lesreg' end as svar;
