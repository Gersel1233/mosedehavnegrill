--
--  ------------------------------------------------------------
--  HVORFOR
--  ------------------------------------------------------------
--  Chefen: lister, de har på en fil, skal kunne lægges ind på
--  iPad'en, så personalet hver dag kan udfylde dem og sætte deres
--  initialer for at vise, at opgaven er gjort. Mikkel: *"det skal
--  være sådan, at de i admin lægger filerne ind, som de selv har et
--  andet sted, og dermed bliver de gjort til arbejdsopgaver,
--  personalet skal udføre."*
--
--  Tre tabeller:
--    opgavelister      — "Åbning", "Lukning", "Rengøring" …, og
--                        hvilke ugedage den gælder
--    opgaver           — linjerne i en liste
--    opgave_udfoert    — hvem (initialer) der gjorde hvad, hvornår,
--                        pr. dag. Teksten gemmes med, så dagens
--                        dokument står, som det så ud — også hvis
--                        opgaven senere rettes eller slettes.
--
--  ⚠️ INITIALER OG IKKE LOGIN. Personalet deler login (booking@),
--  så det er initialerne, der siger, hvem der gjorde det. Login
--  gemmes også (udfoert_af), så man kan se, fra hvilket login det
--  blev sat.
--
--  Cheferne (ejer) lægger lister ind og retter dem; personalet
--  (medarbejder) sætter initialer. Arrangøren ser ingen af delene.
-- ============================================================

begin;

create table if not exists public.opgavelister (
  id           bigint generated by default as identity primary key,
  lokation_id  text        not null,
  navn         text        not null check (length(trim(navn)) between 1 and 80),
  -- 1 = mandag … 7 = søndag. Tom/null = hver dag.
  ugedage      smallint[],
  aktiv        boolean     not null default true,
  raekkefoelge integer     not null default 0,
  kilde        text,       -- filnavnet, listen blev lavet af
  oprettet     timestamptz not null default now()
);

create table if not exists public.opgaver (
  id           bigint generated by default as identity primary key,
  lokation_id  text        not null,
  liste_id     bigint      not null references public.opgavelister(id) on delete cascade,
  tekst        text        not null check (length(trim(tekst)) between 1 and 300),
  -- Overskriften i filen, opgaven stod under ("Dagligt", "Ved lukning").
  afsnit       text,
  -- Skal der skrives en værdi ved opgaven? Fx "Temp. °C" fra egenkontrollen.
  vaerdi_navn  text,
  raekkefoelge integer     not null default 0,
  aktiv        boolean     not null default true,
  oprettet     timestamptz not null default now()
);
alter table public.opgaver add column if not exists afsnit text;
alter table public.opgaver add column if not exists vaerdi_navn text;
create index if not exists opgaver_liste_idx on public.opgaver (liste_id, raekkefoelge);

create table if not exists public.opgave_udfoert (
  id           bigint generated by default as identity primary key,
  lokation_id  text        not null,
  opgave_id    bigint      references public.opgaver(id) on delete set null,
  liste_id     bigint      references public.opgavelister(id) on delete set null,
  dato         date        not null,
  tekst        text        not null,
  liste_navn   text,
  initialer    text        not null check (initialer ~ '^[A-Za-zÆØÅæøå]{1,4}$'),
  vaerdi       text        check (vaerdi is null or length(vaerdi) <= 40),
  udfoert      timestamptz not null default now(),
  udfoert_af   text        default nullif(coalesce(auth.jwt() ->> 'email', ''), '')
);
-- Én opgave er gjort én gang pr. dag.
alter table public.opgave_udfoert add column if not exists vaerdi text;

create unique index if not exists opgave_udfoert_en_pr_dag
  on public.opgave_udfoert (opgave_id, dato) where opgave_id is not null;
create index if not exists opgave_udfoert_dato_idx
  on public.opgave_udfoert (lokation_id, dato desc);

-- Adgangen til tabellerne (reglerne nedenfor siger, HVILKE rækker).
-- Gæsterne (anon) skal ingenting.
grant select, insert, update, delete on public.opgavelister, public.opgaver, public.opgave_udfoert
  to authenticated;
revoke all on public.opgavelister, public.opgaver, public.opgave_udfoert from anon;
grant usage on sequence public.opgavelister_id_seq, public.opgaver_id_seq, public.opgave_udfoert_id_seq
  to authenticated;

alter table public.opgavelister   enable row level security;
alter table public.opgaver        enable row level security;
alter table public.opgave_udfoert enable row level security;

-- LÆSE: alle med admin-adgang (ejer + medarbejder; ikke arrangøren).
drop policy if exists opgavelister_laes on public.opgavelister;
create policy opgavelister_laes on public.opgavelister
  for select using (public.is_admin_for(lokation_id));
drop policy if exists opgaver_laes on public.opgaver;
create policy opgaver_laes on public.opgaver
  for select using (public.is_admin_for(lokation_id));
drop policy if exists opgave_udfoert_laes on public.opgave_udfoert;
create policy opgave_udfoert_laes on public.opgave_udfoert
  for select using (public.is_admin_for(lokation_id));

-- LISTERNE: kun cheferne opretter, retter og sletter.
drop policy if exists opgavelister_skriv on public.opgavelister;
create policy opgavelister_skriv on public.opgavelister
  for all using (public.er_ejer_for(lokation_id))
  with check (public.er_ejer_for(lokation_id));
drop policy if exists opgaver_skriv on public.opgaver;
create policy opgaver_skriv on public.opgaver
  for all using (public.er_ejer_for(lokation_id))
  with check (public.er_ejer_for(lokation_id));

-- INITIALERNE: alle med admin-adgang sætter og fortryder.
-- Ingen update: et flueben rettes ved at fortryde og sætte det igen.
drop policy if exists opgave_udfoert_opret on public.opgave_udfoert;
create policy opgave_udfoert_opret on public.opgave_udfoert
  for insert with check (public.is_admin_for(lokation_id));
drop policy if exists opgave_udfoert_slet on public.opgave_udfoert;
create policy opgave_udfoert_slet on public.opgave_udfoert
  for delete using (public.is_admin_for(lokation_id));

commit;

select 'Arbejdsopgaver er klar — cheferne lægger lister ind, personalet sætter initialer'
  as resultat;
