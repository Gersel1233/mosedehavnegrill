--  ------------------------------------------------------------
--  Kør i Mosede-projektet: epwyjzakvvbxtpvnhvbn
--  Tjek projekt-id'et i adresselinjen, FØR du trykker Run.
--  Kan køres igen uden at ødelægge noget.
--
--  HVORFOR
--  Når hjemmesiden måler (admin → Indstillinger → Målinger og
--  cookies), spørger et banner gæsten først (js/samtykke.js).
--  Forretningen skal kunne VISE, at der blev spurgt, og hvad der
--  blev svaret (GDPR art. 7, stk. 1). Her logges hvert valg —
--  UDEN navn, IP eller andet, der peger på en person: et tilfældigt
--  id fra browseren, valget, versionen af spørgsmålet, siden og tiden.
--
--  Gæsten (anon) må kun SKRIVE en række. Kun cheferne kan læse.
--  Rækker ældre end 2 år slettes af databasen selv ved næste skrivning.
-- ============================================================

begin;

create table if not exists public.samtykke_log (
  id           bigint generated by default as identity primary key,
  lokation_id  text        not null check (lokation_id ~ '^[a-z0-9_-]{1,40}$'),
  samtykke_id  text        not null check (samtykke_id ~ '^[0-9a-f]{8,32}$'),
  version      text        not null check (length(version) <= 60),
  statistik    boolean     not null,
  marketing    boolean     not null,
  side         text        check (side is null or length(side) <= 200),
  tidspunkt    timestamptz not null default now()
);
create index if not exists samtykke_log_tid_idx on public.samtykke_log (lokation_id, tidspunkt desc);

revoke all on public.samtykke_log from anon, authenticated;
grant insert on public.samtykke_log to anon, authenticated;
grant select on public.samtykke_log to authenticated;
grant usage on sequence public.samtykke_log_id_seq to anon, authenticated;

alter table public.samtykke_log enable row level security;

drop policy if exists samtykke_log_skriv on public.samtykke_log;
create policy samtykke_log_skriv on public.samtykke_log
  for insert to anon, authenticated with check (true);

drop policy if exists samtykke_log_laes on public.samtykke_log;
create policy samtykke_log_laes on public.samtykke_log
  for select to authenticated using (public.er_ejer_for(lokation_id));

-- Oprydning: to år er rigeligt til at kunne dokumentere et samtykke.
create or replace function public.samtykke_log_ryd()
 returns trigger
 language plpgsql
 security definer
 set search_path to ''
as $function$
begin
  if random() < 0.02 then
    delete from public.samtykke_log where tidspunkt < now() - interval '2 years';
  end if;
  return null;
end $function$;

drop trigger if exists samtykke_log_ryd on public.samtykke_log;
create trigger samtykke_log_ryd after insert on public.samtykke_log
  for each statement execute function public.samtykke_log_ryd();

commit;

select 'Cookie-samtykker logges nu (uden navn) — og ryddes efter 2 år' as resultat;
